"""Multivariate symbolic differential-operator algebra.

A :class:`NormalOp` represents a differential operator in *normal form*::

    D P = sum_mu f_mu(z) ∂^mu P

with multi-indices ``mu`` (tuples of non-negative ints, one entry per
phase-space variable) and :mod:`sympy` coefficients ``f_mu``.  Multiplication
is operator composition via the multivariate Leibniz rule.

:func:`normal_to_flux` rewrites a normal form into *flux form*::

    D P = sum_mu ∂^mu [ g_mu(z) P ]

using the exact identity

    f ∂^mu P = sum_{nu <= mu} (-1)^|nu| C(mu, nu) ∂^{mu-nu}[ (∂^nu f) P ],

where ``C(mu, nu)`` is the componentwise product of binomial coefficients and
``nu <= mu`` is componentwise.  No truncation happens here: every lower-order
flux term generated by the Leibniz rule is kept.
"""

from __future__ import annotations

from itertools import product
from math import comb, factorial

import sympy as sp

__all__ = [
    "NormalOp",
    "normal_to_flux",
    "multi_index_order",
    "multi_index_factorial",
    "sub_multi_indices",
]

MultiIndex = tuple[int, ...]


def multi_index_order(mu: MultiIndex) -> int:
    return sum(mu)


def multi_index_factorial(mu: MultiIndex) -> int:
    out = 1
    for m in mu:
        out *= factorial(m)
    return out


def sub_multi_indices(mu: MultiIndex) -> list[MultiIndex]:
    """All multi-indices ``nu`` with ``nu <= mu`` componentwise."""
    return [tuple(k) for k in product(*(range(m + 1) for m in mu))]


def _binomial_product(mu: MultiIndex, nu: MultiIndex) -> int:
    out = 1
    for m, n in zip(mu, nu, strict=True):
        out *= comb(m, n)
    return out


def _add(mu: MultiIndex, nu: MultiIndex) -> MultiIndex:
    return tuple(m + n for m, n in zip(mu, nu, strict=True))


def _sub(mu: MultiIndex, nu: MultiIndex) -> MultiIndex:
    return tuple(m - n for m, n in zip(mu, nu, strict=True))


def diff_multi(expr: sp.Expr, variables: tuple[sp.Symbol, ...], nu: MultiIndex) -> sp.Expr:
    """Apply the mixed partial derivative ``∂^nu`` to ``expr``."""
    for var, n in zip(variables, nu, strict=True):
        if n:
            expr = sp.diff(expr, var, n)
    return expr


class NormalOp:
    """Normal-form differential operator ``sum_mu f_mu(z) ∂^mu``."""

    def __init__(
        self,
        variables: tuple[sp.Symbol, ...],
        terms: dict[MultiIndex, sp.Expr] | None = None,
    ):
        self.variables = tuple(variables)
        self.dim = len(self.variables)
        self.terms: dict[MultiIndex, sp.Expr] = {}
        for mu, coeff in (terms or {}).items():
            self._check(mu)
            if coeff != 0:
                self.terms[tuple(mu)] = coeff

    # ------------------------------------------------------------------
    def _check(self, mu: MultiIndex) -> None:
        if len(mu) != self.dim or any(m < 0 for m in mu):
            raise ValueError(f"Bad multi-index {mu} for dimension {self.dim}.")

    @staticmethod
    def zero(variables) -> NormalOp:
        return NormalOp(variables)

    @staticmethod
    def identity(variables) -> NormalOp:
        return NormalOp(variables, {tuple([0] * len(variables)): sp.Integer(1)})

    @staticmethod
    def multiply_by(variables, expr: sp.Expr) -> NormalOp:
        """Multiplication operator ``P -> expr * P``."""
        return NormalOp(variables, {tuple([0] * len(variables)): sp.sympify(expr)})

    @staticmethod
    def partial(variables, axis: int, coeff=sp.Integer(1)) -> NormalOp:
        """Single derivative ``coeff * ∂_{variables[axis]}``."""
        mu = [0] * len(variables)
        mu[axis] = 1
        return NormalOp(variables, {tuple(mu): sp.sympify(coeff)})

    # ------------------------------------------------------------------
    def __add__(self, other: NormalOp) -> NormalOp:
        self._compatible(other)
        terms = dict(self.terms)
        for mu, coeff in other.terms.items():
            terms[mu] = terms.get(mu, sp.Integer(0)) + coeff
        return NormalOp(self.variables, terms)

    def scale(self, factor) -> NormalOp:
        factor = sp.sympify(factor)
        return NormalOp(self.variables, {mu: factor * c for mu, c in self.terms.items()})

    def __mul__(self, other: NormalOp) -> NormalOp:
        """Operator composition ``self ∘ other`` (``other`` acts first)."""
        self._compatible(other)
        terms: dict[MultiIndex, sp.Expr] = {}
        for mu, f in self.terms.items():
            for nu, g in other.terms.items():
                for k in sub_multi_indices(mu):
                    coeff = (
                        _binomial_product(mu, k) * f * diff_multi(g, self.variables, k)
                    )
                    lam = _add(_sub(mu, k), nu)
                    terms[lam] = terms.get(lam, sp.Integer(0)) + coeff
        return NormalOp(self.variables, terms)

    def _compatible(self, other: NormalOp) -> None:
        if self.variables != other.variables:
            raise ValueError("NormalOp variables mismatch.")

    def max_order(self) -> int:
        return max((multi_index_order(mu) for mu in self.terms), default=0)

    def __repr__(self) -> str:
        return f"NormalOp({self.terms!r})"


def normal_to_flux(op: NormalOp) -> dict[MultiIndex, sp.Expr]:
    """Convert normal form ``sum_mu f_mu ∂^mu P`` to flux coefficients ``g_mu``
    such that the operator equals ``sum_mu ∂^mu[ g_mu(z) P ]``.

    The conversion is exact: all lower-order flux terms produced by the
    multivariate Leibniz rule are retained.
    """
    flux: dict[MultiIndex, sp.Expr] = {}
    for mu, f in op.terms.items():
        for nu in sub_multi_indices(mu):
            lam = _sub(mu, nu)
            sign = -1 if multi_index_order(nu) % 2 else 1
            coeff = _binomial_product(mu, nu) * diff_multi(f, op.variables, nu)
            flux[lam] = flux.get(lam, sp.Integer(0)) + sign * coeff
    return {mu: coeff for mu, coeff in flux.items() if coeff != 0}
